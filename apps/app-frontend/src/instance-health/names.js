/** Readable name for a mod id, or null when unknown. */
export const knownName = (id) => PLATFORM[id] || KNOWN[id] || null
/** "neoforge" -> "NeoForge"; unknown loaders are returned as is. */
export const loaderName = (loader) =>
  LOADER_LABELS[String(loader ?? '').toLowerCase()] ||
  (String(loader ?? '').toLowerCase() === 'vanilla' ? 'Vanilla' : loader ?? '')
